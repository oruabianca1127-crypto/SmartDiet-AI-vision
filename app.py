import os
import pandas as pd
from flask import Flask, jsonify, request
from flask_cors import CORS
from google import genai  # Official Google GenAI SDK
from google.genai import types
from rapidfuzz import process

app = Flask(__name__)
CORS(app)  # Allows your Z.com website to talk to this backend

# Initialize the Gemini client (Make sure your GEMINI_API_KEY is set in your environment variables)
# On Render, you can add GEMINI_API_KEY in the Environment settings tab.
client = genai.Client(api_key=os.environ.get("GEMINI_API_KEY"))

# Load your CSV dataset once when the server starts up[cite: 1]
df = pd.read_csv("PFD_2000_yehey.csv", encoding="latin1")
df["Food_lower"] = df["Food Names"].str.lower()

CONFIDENT_SCORE_THRESHOLD = 95
SUGGESTION_SCORE_THRESHOLD = 85


@app.route("/analyze-food", methods=["POST"])
def analyze_food():
  # Check if an image file was sent from the website
  if "image" not in request.files:
    return jsonify({"error": "No image uploaded."}), 400

  image_file = request.files["image"]

  # Save the image temporarily so Gemini can read it
  temp_path = "temp_food_image.jpg"
  image_file.save(temp_path)

  try:
    # 1. Use Gemini Vision to identify the food and estimate grams from the photo
    with open(temp_path, "rb") as f:
      image_bytes = f.read()

    prompt = (
        "Analyze this food image. Identify the Filipino food items present and"
        " estimate their weight in grams based on standard serving sizes."
        " Return your answer *only* as a comma-separated string in this exact"
        " format: foodname:grams, foodname:grams. For example: adobo:150,"
        " rice:200. Do not include any other text or markdown."
    )

    response = client.models.generate_content(
        model="gemini-3.8-flash",
        contents=[
            prompt,
            types.Part.from_bytes(data=image_bytes, mime_type="image/jpeg"),
        ],
        config=types.GenerateContentConfig(
            temperature=0.2
        ),  # Low temperature keeps responses structured and predictable
    )

    user_food_string = response.text.strip().lower()

  except Exception as e:
    if os.path.exists(temp_path):
      os.remove(temp_path)
    return jsonify({"error": f"AI Vision analysis failed: {str(e)}"}), 500

  # Clean up temporary image file
  if os.path.exists(temp_path):
    os.remove(temp_path)

  # 2. Parse the string generated by Gemini (Adapting your original parsing logic)
  food_pairs_raw = user_food_string.split(",")
  food_inputs = []

  for pair_str in food_pairs_raw:
    parts = pair_str.strip().split(":")
    if len(parts) == 2:
      query = parts[0].strip()
      try:
        grams = float(parts[1].strip())
        if grams > 0:
          food_inputs.append({"query": query, "grams": grams})
      except ValueError:
        continue

  if not food_inputs:
    return jsonify({
        "ai_output": user_food_string,
        "error": "Could not parse valid food items from the photo analysis.",
    })

  # 3. Run your exact RapidFuzz matching & calculation loop[cite: 1]
  item_results = []
  total_calories = 0.0
  total_carbs = 0.0
  total_protein = 0.0
  total_fat = 0.0

  for food_item in food_inputs:
    query = food_item["query"]
    grams = food_item["grams"]

    matches = process.extract(query, df["Food_lower"], limit=None)
    if not matches:
      continue

    best_match_name, best_score, best_index = matches[0]
    chosen_row = None

    if best_score >= CONFIDENT_SCORE_THRESHOLD:
      chosen_row = df.iloc[best_index]
    elif best_score >= SUGGESTION_SCORE_THRESHOLD:
      # Automatically pick the best suggestion above threshold for seamless web use
      filtered_matches = [m for m in matches if m[1] >= SUGGESTION_SCORE_THRESHOLD]
      if filtered_matches:
        chosen_row = df.iloc[filtered_matches[0][2]]

    if chosen_row is not None:
      calories = chosen_row["Calories per gram"] * grams
      carbs = chosen_row["Carbohydrates per gram"] * grams
      protein = chosen_row["Protein per gram"] * grams
      fat = chosen_row["Fats per gram"] * grams

      item_results.append({
          "query": query,
          "matched_food": chosen_row["Food Names"],
          "score": best_score,
          "grams": grams,
          "calories": round(calories, 2),
          "carbs": round(carbs, 2),
          "protein": round(protein, 2),
          "fat": round(fat, 2),
      })

      total_calories += calories
      total_carbs += carbs
      total_protein += protein
      total_fat += fat

  return jsonify({
      "detected_string": user_food_string,
      "items": item_results,
      "totals": {
          "calories": round(total_calories, 2),
          "carbs": round(total_carbs, 2),
          "protein": round(total_protein, 2),
          "fat": round(total_fat, 2),
      },
  })


if __name__ == "__main__":
  app.run(port=5000)